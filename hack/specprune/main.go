// Command specprune turns the platform's private OpenAPI specs into the
// pruned public copies vendored under internal/api/specs.
//
// This repository is public, so nothing reaches it unless the allowlist
// names it. For each service the tool keeps only the allowlisted operations
// and the components they reference, removes every x- extension, security
// requirement and server, drops the fields the allowlist names, applies
// description overrides, and then refuses to write anything if a remaining
// description matches a deny pattern or a property name looks internal and
// has not been reviewed.
//
// Usage:
//
//	specprune -allowlist internal/api/specs/allowlist.yaml -src <dir> -out internal/api/specs
//
// <dir> holds the source specs at the paths the allowlist names, checked out
// at the allowlist's source ref (see hack/vendor-specs.sh).
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"go.yaml.in/yaml/v3"
)

// Allowlist is the reviewed description of what may be published.
type Allowlist struct {
	Source struct {
		Repo string `yaml:"repo"`
		Ref  string `yaml:"ref"`
	} `yaml:"source"`
	// DenyPatterns are regular expressions no published description may
	// match.
	DenyPatterns []string `yaml:"deny_patterns"`
	// SuspectFields are regular expressions for property names that need a
	// human decision: each match must be dropped or listed under reviewed.
	SuspectFields []string           `yaml:"suspect_fields"`
	Services      map[string]Service `yaml:"services"`
}

// Service is one source spec.
type Service struct {
	Path       string   `yaml:"path"`
	Operations []string `yaml:"operations"`
	// DropFields removes properties: "schemas/<Name>.<field>" or
	// "requestBodies/<Name>.<field>".
	DropFields []string `yaml:"drop_fields"`
	// Reviewed lists suspect properties a human decided to publish, in the
	// same form as DropFields.
	Reviewed []string `yaml:"reviewed"`
	// Descriptions replaces descriptions by JSON pointer; an empty value
	// removes the description.
	Descriptions map[string]string `yaml:"descriptions"`
}

var httpMethods = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"}

func main() {
	allowPath := flag.String("allowlist", "internal/api/specs/allowlist.yaml", "allowlist file")
	src := flag.String("src", "", "directory holding the source specs")
	out := flag.String("out", "internal/api/specs", "output directory")
	flag.Parse()

	if err := run(*allowPath, *src, *out); err != nil {
		fmt.Fprintln(os.Stderr, "specprune:", err)
		os.Exit(1)
	}
}

func run(allowPath, src, out string) error {
	if src == "" {
		return errors.New("-src is required")
	}
	b, err := os.ReadFile(allowPath) //nolint:gosec // path from a flag
	if err != nil {
		return err
	}
	var al Allowlist
	dec := yaml.NewDecoder(bytes.NewReader(b))
	dec.KnownFields(true)
	if err := dec.Decode(&al); err != nil {
		return fmt.Errorf("%s: %w", allowPath, err)
	}
	deny, err := compileAll(al.DenyPatterns)
	if err != nil {
		return err
	}
	suspect, err := compileAll(al.SuspectFields)
	if err != nil {
		return err
	}

	names := make([]string, 0, len(al.Services))
	for name := range al.Services {
		names = append(names, name)
	}
	slices.Sort(names)

	var problems []string
	results := map[string][]byte{}
	for _, name := range names {
		svc := al.Services[name]
		raw, err := os.ReadFile(filepath.Join(src, svc.Path)) //nolint:gosec // paths come from the reviewed allowlist
		if err != nil {
			return err
		}
		pruned, probs, err := prune(raw, &svc, deny, suspect)
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		for _, p := range probs {
			problems = append(problems, name+": "+p)
		}
		header := fmt.Sprintf("# Code generated by hack/specprune from %s@%s:%s. DO NOT EDIT.\n"+
			"# Pruned to the operations in allowlist.yaml; regenerate with `make vendor-specs`.\n",
			al.Source.Repo, al.Source.Ref, svc.Path)
		results[name] = append([]byte(header), pruned...)
	}
	if len(problems) > 0 {
		return fmt.Errorf("refusing to publish:\n  %s", strings.Join(problems, "\n  "))
	}
	for _, name := range names {
		//nolint:gosec // committed source files are world-readable
		if err := os.WriteFile(filepath.Join(out, name+".yaml"), results[name], 0o644); err != nil {
			return err
		}
	}
	return nil
}

func compileAll(patterns []string) ([]*regexp.Regexp, error) {
	res := make([]*regexp.Regexp, 0, len(patterns))
	for _, p := range patterns {
		re, err := regexp.Compile(p)
		if err != nil {
			return nil, fmt.Errorf("pattern %q: %w", p, err)
		}
		res = append(res, re)
	}
	return res, nil
}

// prune returns the pruned spec and any reasons it must not be published.
func prune(raw []byte, svc *Service, deny, suspect []*regexp.Regexp) ([]byte, []string, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return nil, nil, err
	}
	root := doc.Content[0]

	// Top level: keep only what a client needs.
	keepKeys(root, "openapi", "info", "paths", "components")
	if info := get(root, "info"); info != nil {
		keepKeys(info, "title", "version")
	}

	if err := pruneOperations(get(root, "paths"), svc.Operations); err != nil {
		return nil, nil, err
	}
	stripExtensions(root)
	if err := dropFields(root, svc.DropFields); err != nil {
		return nil, nil, err
	}
	pruneComponents(root)
	if err := overrideDescriptions(root, svc.Descriptions); err != nil {
		return nil, nil, err
	}

	var problems []string
	walkDescriptions(root, "", func(ptr, text string) {
		for _, re := range deny {
			if re.MatchString(text) {
				problems = append(problems, fmt.Sprintf("description at %s matches deny pattern %q", ptr, re))
			}
		}
	})
	for _, f := range propertyNames(root) {
		if slices.Contains(svc.Reviewed, f) {
			continue
		}
		for _, re := range suspect {
			if re.MatchString(f[strings.LastIndex(f, ".")+1:]) {
				problems = append(problems, fmt.Sprintf("property %s looks internal: drop it or list it under reviewed", f))
			}
		}
	}

	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return nil, nil, err
	}
	return buf.Bytes(), problems, enc.Close()
}

// pruneOperations keeps only allowlisted operations and removes path items
// left without any.
func pruneOperations(paths *yaml.Node, ops []string) error {
	if paths == nil {
		return errors.New("no paths")
	}
	found := map[string]bool{}
	var kept []*yaml.Node
	for i := 0; i < len(paths.Content); i += 2 {
		item := paths.Content[i+1]
		var itemKept []*yaml.Node
		hasOp := false
		for j := 0; j < len(item.Content); j += 2 {
			k, v := item.Content[j], item.Content[j+1]
			if !slices.Contains(httpMethods, k.Value) {
				itemKept = append(itemKept, k, v)
				continue
			}
			id := scalar(get(v, "operationId"))
			if !slices.Contains(ops, id) {
				continue
			}
			found[id] = true
			hasOp = true
			deleteKey(v, "security")
			itemKept = append(itemKept, k, v)
		}
		if hasOp {
			item.Content = itemKept
			kept = append(kept, paths.Content[i], item)
		}
	}
	paths.Content = kept
	for _, id := range ops {
		if !found[id] {
			return fmt.Errorf("allowlisted operation %s not found", id)
		}
	}
	return nil
}

// stripExtensions removes every x- key. A schema whose Go type came from
// x-go-type and that has no type of its own becomes a string, which is how
// those types (resource quantities) serialise.
func stripExtensions(n *yaml.Node) {
	switch n.Kind { //nolint:exhaustive // scalars and aliases carry no keys
	case yaml.MappingNode:
		hadGoType := false
		var kept []*yaml.Node
		for i := 0; i < len(n.Content); i += 2 {
			k := n.Content[i]
			if strings.HasPrefix(k.Value, "x-") {
				if k.Value == "x-go-type" {
					hadGoType = true
				}
				continue
			}
			kept = append(kept, k, n.Content[i+1])
		}
		n.Content = kept
		if hadGoType && get(n, "type") == nil && get(n, "$ref") == nil {
			n.Content = append([]*yaml.Node{str("type"), str("string")}, n.Content...)
		}
		for _, c := range n.Content {
			stripExtensions(c)
		}
	case yaml.SequenceNode, yaml.DocumentNode:
		for _, c := range n.Content {
			stripExtensions(c)
		}
	}
}

// dropFields removes properties named "schemas/<Name>.<field>" or
// "requestBodies/<Name>.<field>", and their entries in required.
func dropFields(root *yaml.Node, fields []string) error {
	for _, f := range fields {
		obj, err := objectSchema(root, f[:strings.LastIndex(f, ".")])
		if err != nil {
			return fmt.Errorf("drop_fields %s: %w", f, err)
		}
		field := f[strings.LastIndex(f, ".")+1:]
		props := get(obj, "properties")
		if props == nil || get(props, field) == nil {
			return fmt.Errorf("drop_fields %s: no such property", f)
		}
		deleteKey(props, field)
		if req := get(obj, "required"); req != nil {
			var kept []*yaml.Node
			for _, r := range req.Content {
				if r.Value != field {
					kept = append(kept, r)
				}
			}
			req.Content = kept
		}
	}
	return nil
}

// objectSchema resolves "schemas/<Name>" or "requestBodies/<Name>" to the
// object schema holding properties.
func objectSchema(root *yaml.Node, ref string) (*yaml.Node, error) {
	kind, name, ok := strings.Cut(ref, "/")
	if !ok {
		return nil, fmt.Errorf("want schemas/<Name> or requestBodies/<Name>, got %q", ref)
	}
	n := get(get(get(root, "components"), kind), name)
	if n == nil {
		return nil, errors.New("not found")
	}
	if kind == "requestBodies" {
		n = get(get(get(n, "content"), "application/json"), "schema")
	}
	if n == nil {
		return nil, errors.New("no JSON schema")
	}
	return n, nil
}

// pruneComponents keeps only components reachable from the paths.
func pruneComponents(root *yaml.Node) {
	comps := get(root, "components")
	if comps == nil {
		return
	}
	reachable := map[string]bool{}
	var queue []string
	collectRefs(get(root, "paths"), &queue)
	for len(queue) > 0 {
		ref := queue[0]
		queue = queue[1:]
		if reachable[ref] {
			continue
		}
		reachable[ref] = true
		kind, name, _ := strings.Cut(strings.TrimPrefix(ref, "#/components/"), "/")
		if n := get(get(comps, kind), name); n != nil {
			collectRefs(n, &queue)
		}
	}
	var keptKinds []*yaml.Node
	for i := 0; i < len(comps.Content); i += 2 {
		kind, items := comps.Content[i], comps.Content[i+1]
		var kept []*yaml.Node
		for j := 0; j < len(items.Content); j += 2 {
			if reachable["#/components/"+kind.Value+"/"+items.Content[j].Value] {
				kept = append(kept, items.Content[j], items.Content[j+1])
			}
		}
		items.Content = kept
		if len(kept) > 0 {
			keptKinds = append(keptKinds, kind, items)
		}
	}
	comps.Content = keptKinds
}

func collectRefs(n *yaml.Node, out *[]string) {
	if n == nil {
		return
	}
	if n.Kind == yaml.MappingNode {
		for i := 0; i < len(n.Content); i += 2 {
			if n.Content[i].Value == "$ref" {
				*out = append(*out, n.Content[i+1].Value)
			}
		}
	}
	for _, c := range n.Content {
		collectRefs(c, out)
	}
}

// overrideDescriptions sets or removes descriptions by JSON pointer.
func overrideDescriptions(root *yaml.Node, overrides map[string]string) error {
	ptrs := make([]string, 0, len(overrides))
	for p := range overrides {
		ptrs = append(ptrs, p)
	}
	slices.Sort(ptrs)
	for _, ptr := range ptrs {
		parent, key, err := resolveParent(root, ptr)
		if err != nil {
			return fmt.Errorf("descriptions %s: %w", ptr, err)
		}
		if key != "description" {
			return fmt.Errorf("descriptions %s: pointer must end in /description", ptr)
		}
		text := overrides[ptr]
		switch existing := get(parent, key); {
		case text == "":
			deleteKey(parent, key)
		case existing != nil:
			existing.Value, existing.Style = text, 0
		default:
			parent.Content = append(parent.Content, str(key), str(text))
		}
	}
	return nil
}

// resolveParent returns the mapping holding the last segment of ptr.
func resolveParent(root *yaml.Node, ptr string) (*yaml.Node, string, error) {
	segs := strings.Split(strings.TrimPrefix(ptr, "#/"), "/")
	n := root
	for _, s := range segs[:len(segs)-1] {
		s = strings.NewReplacer("~1", "/", "~0", "~").Replace(s)
		if n = get(n, s); n == nil {
			return nil, "", fmt.Errorf("segment %q not found", s)
		}
	}
	return n, segs[len(segs)-1], nil
}

// walkDescriptions calls fn for every description and summary.
func walkDescriptions(n *yaml.Node, ptr string, fn func(ptr, text string)) {
	switch n.Kind { //nolint:exhaustive // only mappings and sequences nest
	case yaml.MappingNode:
		for i := 0; i < len(n.Content); i += 2 {
			k, v := n.Content[i].Value, n.Content[i+1]
			p := ptr + "/" + strings.NewReplacer("~", "~0", "/", "~1").Replace(k)
			if (k == "description" || k == "summary" || k == "title") && v.Kind == yaml.ScalarNode {
				fn("#"+p, v.Value)
				continue
			}
			walkDescriptions(v, p, fn)
		}
	case yaml.SequenceNode:
		for i, c := range n.Content {
			walkDescriptions(c, fmt.Sprintf("%s/%d", ptr, i), fn)
		}
	}
}

// propertyNames lists every property of component schemas and request
// bodies as "schemas/<Name>.<field>" or "requestBodies/<Name>.<field>".
// Nested inline objects are reported under their component.
func propertyNames(root *yaml.Node) []string {
	var out []string
	comps := get(root, "components")
	for _, kind := range []string{"schemas", "requestBodies"} {
		items := get(comps, kind)
		if items == nil {
			continue
		}
		for i := 0; i < len(items.Content); i += 2 {
			prefix := kind + "/" + items.Content[i].Value
			collectProps(items.Content[i+1], prefix, &out)
		}
	}
	return out
}

func collectProps(n *yaml.Node, prefix string, out *[]string) {
	if n.Kind != yaml.MappingNode {
		for _, c := range n.Content {
			collectProps(c, prefix, out)
		}
		return
	}
	for i := 0; i < len(n.Content); i += 2 {
		k, v := n.Content[i].Value, n.Content[i+1]
		if k == "properties" && v.Kind == yaml.MappingNode {
			for j := 0; j < len(v.Content); j += 2 {
				*out = append(*out, prefix+"."+v.Content[j].Value)
				collectProps(v.Content[j+1], prefix, out)
			}
			continue
		}
		collectProps(v, prefix, out)
	}
}

func get(n *yaml.Node, key string) *yaml.Node {
	if n == nil || n.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1]
		}
	}
	return nil
}

func deleteKey(n *yaml.Node, key string) {
	for i := 0; i < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			n.Content = append(n.Content[:i], n.Content[i+2:]...)
			return
		}
	}
}

func keepKeys(n *yaml.Node, keys ...string) {
	var kept []*yaml.Node
	for i := 0; i < len(n.Content); i += 2 {
		if slices.Contains(keys, n.Content[i].Value) {
			kept = append(kept, n.Content[i], n.Content[i+1])
		}
	}
	n.Content = kept
}

func scalar(n *yaml.Node) string {
	if n == nil {
		return ""
	}
	return n.Value
}

func str(s string) *yaml.Node { return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: s} }
